// Apply the certified Directives dataset to production: 2,552 occurrences.
//
// v5 (16 Aug 2026) — Q DIRECTIVES IS THE ONLY SECTION ON sourceSpansV2 PROVENANCE.
// The adjudication behind this artifact came from scripts/lib/sourceSpansV2.mjs. The other 14
// consumers, and scripts/audit-cross-section.mjs, still import sourceLines() from
// scripts/lib/quotedBlocks.mjs, which is unchanged. Removal here means removal from Q Directives
// and nothing else: post text, Religion & Spirituality assignments, questions, claims,
// predictions, quoted-source evidence and image evidence are all untouched.
//
// `directiveMeta` carries the span, segment and provenance record for each surviving directive,
// read from audit/directives-v5-spans.json. It is what lets the reader highlight the COMPLETE
// sentence while storing the directive segment inside it.
//
// Source of truth: audit/directives-final.json, which is itself gated — reconcile-directives.mjs
// exits non-zero unless sum(families) === occurrences, every directive carries one of the seven
// agreed families, no unit is double-counted across sources, and no NEEDS_CONTEXT record is in
// the total.
//
// Directives live on the post as `actionRequests` (a string[]) plus a parallel
// `directiveFamilies` map, so the existing UI keeps working while gaining families. In-post
// repeats are preserved: Q writes "Trace background." twice in #1008, and that is two
// directives, exactly as "Coincidence?" twice in #1176 is two questions.
//
// The 228 Question <-> Directive overlaps are INTENTIONAL. An information-request imperative
// ("Define 'Projection'.") and a directive-wrapped question ("Ask yourself, why...?") each
// count once in Questions and once in Directives, never twice inside either.
//
// Idempotent: rebuilds actionRequests from the certified artifact each run, so an export cannot
// silently revert it.
//
//   node scripts/apply-directives.mjs [--dry]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { clean, key } from './lib/segment.mjs'
// The certified family detector, and the ruleset for the residue it cannot name. Two files on
// purpose: the detector must not widen, or this batch would silently re-family certified rows.
import { familyOf } from './lib/imperative.mjs'
import { queueFamilyOf } from './lib/queueDirectiveFamily.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA = path.join(ROOT, 'public', 'data')
const dry = process.argv.includes('--dry')

const posts = JSON.parse(fs.readFileSync(path.join(DATA, 'posts.json'), 'utf8'))
const questions = JSON.parse(fs.readFileSync(path.join(DATA, 'questions.json'), 'utf8')).filter(q => !q.editorialNormalization)
const final = JSON.parse(fs.readFileSync(path.join(ROOT, 'audit/directives-final.json'), 'utf8'))
const SPANS = path.join(ROOT, 'audit/directives-v5-spans.json')
const v5spans = fs.existsSync(SPANS) ? JSON.parse(fs.readFileSync(SPANS, 'utf8')).spans : {}

const FAMILIES = ['cognition', 'research', 'morale', 'attention', 'operational', 'dissemination', 'prohibition']
const flat = t => clean(t).replace(/\s+/g, ' ').trim()

const byPost = new Map()
// ── Owner rulings ───────────────────────────────────────────────────────────
// Merged into the certified rows before materialising, so they travel through the same QA and
// the same postAnalysis write as everything else. Held outside directives-final.json because that
// artifact is regenerated by the certification pass.
const ORULES = path.join(ROOT, 'audit/directives-owner-rulings.json')
let ownerDirectives = 0
if (fs.existsSync(ORULES)) {
  for (const r of JSON.parse(fs.readFileSync(ORULES, 'utf8')).rulings ?? []) {
    if (final.rows.some(x => x.postNum === r.postNum && x.qSourceText === r.sourceText)) continue
    final.rows.push({
      postNum: r.postNum, postId: r.postId, qSourceText: r.sourceText,
      family: r.family, confidence: 'OWNER', alsoCertifiedQuestion: false,
      klass: 'Q_DIRECTIVE', storedAsActionRequest: true, source: 'owner ruling',
      provenance: `owner ruling ${r.ruledOn} — ${r.reasoning}`,
    })
    ownerDirectives++
  }
}

// ── The unhighlighted-sentence queue, ruled by the owner (2026-08-20) ────────
//
// Same merge point, same QA, one different problem: a directive needs a FAMILY, and the review
// named a section rather than a family. familyOf() — the detector that produced the certified
// 2,552 and their family split — is asked first and its answer is always kept, so this batch
// cannot re-family a single certified row. It leaves 378 of the 486 as 'other', because it keys on
// a leading imperative verb and this queue is dominated by shapes that have none: "Logical
// thinking.", "Worth remembering.", "Thank you Anon.", "UNITED WE STAND." Those are decided by
// lib/queueDirectiveFamily.mjs, which states the FUNCTION each rule is claiming and returns
// 'other' rather than absorbing anything it cannot name — the gate below then refuses.
//
// Occurrence-aware, like every other layer here: the audit emitted one row per UNIT, so a line Q
// wrote twice arrives twice and is certified twice.
const QUEUE = path.join(ROOT, 'audit/unhighlighted-owner-rulings.json')
const queueRulings = (fs.existsSync(QUEUE) ? JSON.parse(fs.readFileSync(QUEUE, 'utf8')).rulings ?? [] : [])
  .filter(r => r.section === 'directives')
const queueStats = { added: 0, already: 0, byFamily: {} }
{
  const have = new Map()
  for (const x of final.rows) { const k = `${x.postNum}|${key(x.qSourceText)}`; have.set(k, (have.get(k) ?? 0) + 1) }
  const seen = new Map()
  for (const r of queueRulings) {
    const k = `${r.postNum}|${key(r.sourceText)}`
    const done = seen.get(k) ?? 0
    seen.set(k, done + 1)
    if (done < (have.get(k) ?? 0)) { queueStats.already++; continue }
    const detected = familyOf(r.sourceText)
    const family = detected === 'other' ? queueFamilyOf(r.sourceText, r.postNum) : detected
    queueStats.byFamily[family] = (queueStats.byFamily[family] ?? 0) + 1
    final.rows.push({
      postNum: r.postNum, postId: r.postId, qSourceText: r.sourceText,
      family, confidence: 'OWNER', alsoCertifiedQuestion: false,
      klass: 'Q_DIRECTIVE', storedAsActionRequest: true, source: 'owner ruling',
      familySource: detected === 'other' ? 'queue rules' : 'detector',
      provenance: `owner ruling ${r.ruledOn} — unhighlighted-sentence queue`,
    })
    queueStats.added++
  }
}

for (const r of final.rows) {
  if (!byPost.has(r.postNum)) byPost.set(r.postNum, [])
  byPost.get(r.postNum).push(r)
}

let written = 0, cleared = 0
for (const p of posts) {
  const list = byPost.get(p.postNum)
  if (!list?.length) {
    if (p.actionRequests?.length) cleared++
    p.actionRequests = []
    p.hasRequests = false
    delete p.directiveFamilies
    delete p.directiveMeta
    continue
  }
  p.actionRequests = list.map(r => r.qSourceText)
  p.hasRequests = true
  // v5 span/segment metadata, keyed the same way directiveFamilies is
  const meta = {}
  for (const r of list) {
    const m = v5spans[`${p.postNum}|${key(r.qSourceText)}`]
    if (m) meta[key(r.qSourceText)] = m
  }
  if (Object.keys(meta).length) p.directiveMeta = meta; else delete p.directiveMeta
  // family + overlap metadata, keyed by the normalised text so the UI can look it up
  p.directiveFamilies = {}
  for (const r of list) {
    p.directiveFamilies[key(r.qSourceText)] = {
      family: r.family,
      alsoQuestion: Boolean(r.alsoCertifiedQuestion),
    }
  }
  written += list.length
}

// ── QA gate ─────────────────────────────────────────────────────────────────
const all = posts.flatMap(p => (p.actionRequests ?? []).map(t => ({ postNum: p.postNum, text: t })))
const bodyOf = new Map(posts.map(p => [p.postNum, flat(p.text ?? '')]))
const unresolved = all.filter(d => !bodyOf.get(d.postNum)?.includes(flat(d.text)))

const famTally = {}
for (const p of posts) for (const v of Object.values(p.directiveFamilies ?? {})) famTally[v.family] = (famTally[v.family] ?? 0) + 1
const distinct = new Set(all.map(d => key(d.text)))
const postsWith = new Set(all.map(d => d.postNum))

const qKeys = new Set(questions.map(q => `${q.postNum}|${key(q.text)}`))
const qSrc = new Set(questions.filter(q => q.directiveSource).map(q => `${q.postNum}|${key(q.directiveSource)}`))
const overlap = all.filter(d => qKeys.has(`${d.postNum}|${key(d.text)}`) || qSrc.has(`${d.postNum}|${key(d.text)}`))

// A directive must never be counted twice INSIDE the directives section: the same text at the
// same post may repeat only as often as the certified dataset says Q wrote it.
const groups = new Map()
for (const d of all) { const k = `${d.postNum}|${key(d.text)}`; groups.set(k, (groups.get(k) ?? 0) + 1) }
const certGroups = new Map()
for (const r of final.rows) { const k = `${r.postNum}|${key(r.qSourceText)}`; certGroups.set(k, (certGroups.get(k) ?? 0) + 1) }
const countMismatch = [...groups].filter(([k, n]) => certGroups.get(k) !== n)

const checks = [
  // 2,552 + 485 from the unhighlighted-sentence queue (486 ruled, 1 occurrence already
  // certified) = 3,037.
  ['directive occurrences = 3,037', all.length === 3037, all.length],
  ['queue rulings applied = 486', queueStats.added + queueStats.already === 486,
    `${queueStats.added} added + ${queueStats.already} already certified`],
  // The detector's answer is kept wherever it has one; only its residue is decided by the queue
  // ruleset, and nothing may land in 'other'.
  ['no queue directive without a family', !queueStats.byFamily.other, `${queueStats.byFamily.other ?? 0} unnamed`],
  ['owner directive rulings applied = 276', ownerDirectives === 276, ownerDirectives],
  ['all resolve to a source span', unresolved.length === 0, `${all.length - unresolved.length}/${all.length}`],
  // +185: the 485 new occurrences carry 185 wordings Directives did not already hold. The gap is
  // repetition - "Thank you Patriots." and "Happy Hunting." recur across dozens of drops.
  ['distinct = 1,827', distinct.size === 1827, distinct.size],
  // +225 posts gain their first certified directive.
  ['posts with a directive = 1,689', postsWith.size === 1689, postsWith.size],
  // directiveFamilies is a map keyed by normalised text PER POST, so the 53 in-post repeats
  // share one entry: 2,422 occurrences - 53 repeats = 2,369 keys. The occurrence-level
  // invariant (sum of families === 2,422) is enforced upstream by reconcile-directives.mjs;
  // what matters here is that every distinct (post, text) pair carries a family.
  ['every (post, text) pair has a family', Object.values(famTally).reduce((a, b) => a + b, 0) === groups.size, `${Object.values(famTally).reduce((a, b) => a + b, 0)}/${groups.size} keys (${all.length} occurrences incl. ${all.length - groups.size} repeats)`],
  ['every family is one of the seven', Object.keys(famTally).every(f => FAMILIES.includes(f)), Object.keys(famTally).join(', ')],
  ['Question overlap = 230', overlap.length === 230, overlap.length],
  ['no directive counted twice in-section', countMismatch.length === 0, `${countMismatch.length} mismatch(es)`],
]

console.log('\nAPPLY CERTIFIED DIRECTIVES\n')
console.log(`  directives written        : ${written.toLocaleString()}`)
console.log(`  posts cleared of old rows : ${cleared.toLocaleString()}`)
console.log(`
  from the unhighlighted-sentence queue (owner ruling 2026-08-20)`)
console.log(`    +${queueStats.added} occurrences (${queueStats.already} already certified)`)
console.log(`    families: ${Object.entries(queueStats.byFamily).sort((a, b) => b[1] - a[1]).map(([f, n]) => `${f} ${n}`).join(', ')}`)
console.log('\n  by family:')
for (const f of FAMILIES) console.log(`    ${String(famTally[f] ?? 0).padStart(5)}  ${f}`)
console.log('\n  QA GATE')
let failed = 0
for (const [label, ok, got] of checks) { if (!ok) failed++; console.log(`    ${ok ? 'PASS' : 'FAIL'}  ${label.padEnd(38)} ${got}`) }
for (const u of unresolved.slice(0, 6)) console.log(`      unresolved: #${u.postNum} ${JSON.stringify(u.text.slice(0, 58))}`)
for (const [k, n] of countMismatch.slice(0, 6)) console.log(`      count: ${k} wrote ${n}, certified ${certGroups.get(k)}`)

if (failed) { console.error(`\nAborting: ${failed} QA check(s) failed. Nothing written.\n`); process.exit(1) }
if (dry) { console.log('\n--dry: posts.json not written\n'); process.exit(0) }

fs.writeFileSync(path.join(DATA, 'posts.json'), JSON.stringify(posts))
console.log(`\nwrote public/data/posts.json (${(fs.statSync(path.join(DATA, 'posts.json')).size / 1048576).toFixed(1)} MB)\n`)
