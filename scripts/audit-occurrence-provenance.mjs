// A SOCIAL HANDLE IS NOT A CMS SLUG, and the difference decides whether a person survives.
//
// The URL policy was written about publisher URLs: "a path slug is generated by the publisher's
// content-management system, not written by Q". True of
// `washingtonexaminer.com/politics/confidential-banking-records-related-to-hunter-biden-…`.
// NOT true of `twitter.com/CBS_Herridge` — that path segment is a person, and Q chose it. Applying
// the slug rule to it retires Catherine Herridge and Maria Bartiromo from the archive entirely,
// which is not what the ruling said and not what the evidence supports.
//
// So these are separated out and HELD, with no count effect, for a ruling of their own. The policy
// is scoped to what it was written about rather than stretched to cover a case it never saw.
const HANDLE_HOSTS = /^(twitter\.com|x\.com|www\.twitter\.com|mobile\.twitter\.com|facebook\.com|instagram\.com|t\.me|gab\.com|parler\.com|truthsocial\.com|gettr\.com|rumble\.com|youtube\.com)$/
const HANDLE_PREFIX = /^\/(?:@|user\/|c\/|channel\/)?([A-Za-z0-9_.-]{2,40})(?:\/|$)/

/** The handle a URL points at, when the URL is a social profile or a post by one. */
function socialHandle(url) {
  const { host, path } = urlParts(url)
  if (!HANDLE_HOSTS.test(host.toLowerCase())) return null
  const m = HANDLE_PREFIX.exec(path)
  if (!m) return null
  const h = m[1]
  // "status", "watch", "i" and friends are route words, not people.
  if (/^(status|statuses|watch|i|home|search|hashtag|explore|share|embed|intent|photo|video|posts|p)$/i.test(h)) return null
  return h
}

// Per-post work is memoised: the same drop is asked about once per occurrence in it, and #88 alone
// carries 16.
const cache = new Map()
function postFacts(p) {
  if (cache.has(p.postNum)) return cache.get(p.postNum)
  const rendered = runtimeText(p.text ?? '')
  const spans = urlSpans(rendered)
  let prose = ''
  let cursor = 0
  for (const [s, e] of spans) { prose += rendered.slice(cursor, s) + ' '; cursor = e }
  prose += rendered.slice(cursor)
  const quoted = runtimeText((p.quotedPosts ?? []).map(q => q.text ?? '').join(' \n '))
  const hosts = [...new Set(spans.map(([, , u]) => hostnameOf(u)).filter(Boolean))]
  const filenames = [...(p.media ?? []), ...(p.refMedia ?? [])].map(m => m.filename ?? '').filter(Boolean)
  const meta = {}
  for (const f of METADATA_FIELDS) if (p[f]) meta[f] = String(p[f])
  if ((p.topicTags ?? []).length) meta.topicTags = p.topicTags.join(' | ')
  const facts = {
    rendered, prose, quoted, spans, hosts, filenames, meta,
    hasImage: (p.media ?? []).length + (p.refMedia ?? []).length,
  }
  cache.set(p.postNum, facts)
  return facts
}

// ── classify one occurrence ─────────────────────────────────────────────────
function classify(p, alias, entityId) {
  const f = postFacts(p)
  const aliases = aliasesOf.get(entityId)
  const e = byId.get(entityId)

  // 1. the alias the extractor recorded, seen where a reader can see it
  if (completeTokenMatch(f.prose, alias)) return { category: 'visible_complete_token', where: 'prose' }
  if (completeTokenMatch(f.quoted, alias)) return { category: 'visible_complete_token', where: 'quoted content' }

  // 2. ANOTHER registered spelling of the same entity. "HRC" on the page is Hillary Clinton on the
  //    page, whichever spelling the extractor happened to record.
  for (const a of aliases) {
    if (a.toLowerCase() === alias.toLowerCase()) continue
    if (completeTokenMatch(f.prose, a)) return { category: 'visible_alias_variant', where: 'prose', via: a }
    if (completeTokenMatch(f.quoted, a)) return { category: 'visible_alias_variant', where: 'quoted content', via: a }
  }

  // 3a. A SOCIAL HANDLE Q POINTED AT. Checked before every other URL rule, because the rules below
  //     would classify it as a CMS slug or as a stray substring, and both would withdraw a person
  //     Q deliberately named by linking to them.
  for (const [, , url] of f.spans) {
    const handle = socialHandle(url)
    if (!handle) continue
    for (const a of aliases) {
      if (completeTokenMatch(handle.replace(/[_.-]+/g, ' '), a) || (glue(a).length >= 5 && glue(handle) === glue(a))) {
        // OWNER RULING, 2026-08-17: its own category. A handle is a genuine reference and not a
        // prose mention, so it migrates to linked-source metadata as a social account rather than
        // being withdrawn as a slug or kept as a word Q wrote.
        return {
          category: 'social_account_reference',
          urlEvidence: 'social_handle',
          platform: urlParts(url).host.toLowerCase().replace(/^www\.|^mobile\./, ''),
          handle, url, via: a, carriers: [url],
        }
      }
    }
  }

  // 3b. URL evidence. A token match inside a URL first, then the glued brand — which is reported,
  //     never used to decide anything on its own.
  const loc = aliasLocation(f.rendered, alias)
  if (loc.inUrl) {
    if (loc.urlParts.length > 1) return { category: 'ambiguous_provenance', reason: 'the match spans more than one part of the URL', urlEvidence: 'multi' }
    return { category: 'url_source_provenance', urlEvidence: loc.urlParts[0], carriers: f.spans.filter(([, , u]) => aliasLocation(u, alias).inUrl).map(([, , u]) => u) }
  }
  for (const a of aliases) {
    const l2 = aliasLocation(f.rendered, a)
    if (l2.inUrl && l2.urlParts.length === 1) {
      return { category: 'url_source_provenance', urlEvidence: l2.urlParts[0], via: a, carriers: f.spans.filter(([, , u]) => aliasLocation(u, a).inUrl).map(([, , u]) => u) }
    }
  }

  // 4. an image whose FILENAME names the entity — the only image evidence the corpus can carry
  for (const fn of f.filenames) {
    for (const a of aliases) if (completeTokenMatch(fn.replace(/[_-]+/g, ' '), a)) {
      return { category: 'image_provenance_confirmed', filename: fn, via: a }
    }
  }

  // 5. certified metadata that is never rendered as post text
  for (const [field, value] of Object.entries(f.meta)) {
    for (const a of aliases) if (completeTokenMatch(value, a)) {
      return { category: 'nonvisual_metadata_provenance', field, via: a, value: value.slice(0, 160) }
    }
  }

  // 6. the publisher behind a link, spelled as its domain rather than as its name.
  //    OWNER RULING: real source evidence. Classified url_source_provenance, never "unsupported".
  for (const host of f.hosts) {
    for (const a of aliases) if (gluedHostMatch(host, a)) {
      return { category: 'url_source_provenance', urlEvidence: 'hostname_glued', host, via: a,
        carriers: f.spans.map(([, , u]) => u).filter(u => hostnameOf(u) === host) }
    }
  }

  // 7. THE BOUNDARY DEFECT. The alias exists in the drop only inside a longer word.
  //
  // TWO RULINGS MEET HERE AND THEY DISAGREE, so neither is applied over the other. The boundary
  // ruling says a substring is not a mention unless approved provenance supports it, and an
  // unverified image is explicitly not approved provenance. The image ruling says the
  // image_provenance_unconfirmed records "remain certified for now". Where a substring occurrence
  // sits in a drop that carries an image, both are true and they point opposite ways — so the
  // occurrence is classified honestly as a substring extraction and HELD, with no count effect,
  // rather than being auto-withdrawn under one ruling or hidden under the other.
  const inside = containingWords(f.rendered, alias)
  if (inside.length) {
    // OWNER RULING, 2026-08-17: where a drop carries an image, the occurrence is classified
    // image_provenance_unconfirmed, not as a substring extraction. An attached image COULD contain
    // the entity and nothing in the corpus can say otherwise, so the certified count stands until
    // an editor looks at the picture. The substring evidence is kept on the row — the finding is
    // not erased by the reclassification, it is just no longer the verdict.
    if (f.hasImage) {
      return { category: 'image_provenance_unconfirmed', images: f.hasImage, alsoSubstringOf: inside, reclassifiedFrom: 'invalid_substring_extraction' }
    }
    return { category: 'invalid_substring_extraction', containingWords: inside }
  }

  // 8. an image is attached, and nothing establishes what is in it
  if (f.hasImage) return { category: 'image_provenance_unconfirmed', images: f.hasImage }

  return { category: 'no_supported_provenance' }
}

// ── walk the corpus ─────────────────────────────────────────────────────────
const rows = []
const substrings = []
const withdrawals = []
const socialAccounts = []
const attribution = { unique: 0, ambiguous: 0 }

for (const p of posts) {
  const named = p.postAnalysis?.namedEntities ?? []
  for (let i = 0; i < named.length; i++) {
    const alias = named[i]
    const occurrenceId = `#${p.postNum}:${i}`
    const candidates = (aliasOwners.get(String(alias).toLowerCase()) ?? []).filter(id => postsOf.get(id).has(p.postNum))

    if (candidates.length !== 1) {
      attribution.ambiguous++
      rows.push({
        occurrenceId, postNum: p.postNum, index: i, alias,
        entityId: null, canonical: null, entityType: null,
        category: 'ambiguous_provenance',
        detail: candidates.length > 1
          ? `${candidates.length} live entities claim "${alias}" and list this drop: ${candidates.map(id => byId.get(id).canonical).join(', ')}`
          : `no live entity claims "${alias}" in this drop`,
        proposedAction: 'keep — attribution must be settled by an occurrence-level ruling, not by a matcher',
        certifiedCountEffect: 0,
      })
      continue
    }
    attribution.unique++
    const entityId = candidates[0]
    const e = byId.get(entityId)
    const v = classify(p, alias, entityId)

    const row = {
      occurrenceId, postNum: p.postNum, index: i, alias,
      entityId, canonical: e.canonical, entityType: e.type,
      category: v.category,
      evidence: v,
      proposedAction: 'keep',
      certifiedCountEffect: 0,
    }

    if (v.category === 'url_source_provenance') {
      // The ruled policy, unchanged: a domain is a publisher and migrates; a slug and a query term
      // are artefacts of the link and are withdrawn. One category, two actions, both stated.
      const part = v.urlEvidence
      row.proposedAction = (part === 'hostname' || part === 'hostname_glued')
        ? 'migrate-to-linked-source' : 'remove-annotation'
      row.certifiedCountEffect = -1
    } else if (v.category === 'social_account_reference') {
      row.proposedAction = 'migrate-to-social-account'
      row.certifiedCountEffect = -1
    } else if (v.category === 'invalid_substring_extraction') {
      row.proposedAction = 'remove-annotation'
      row.certifiedCountEffect = -1
    } else if (v.category === 'image_provenance_unconfirmed') {
      row.proposedAction = 'hold — certified until an editor examines the source image; no public text hover'
      row.privateProvenanceReview = true
    } else if (v.category === 'no_supported_provenance') {
      // OWNER RULING, 2026-08-17: withdrawal approved for the population the ruling was made about.
      //
      // SCOPED TO THAT POPULATION ON PURPOSE. The corpus-wide pass finds 85 unsupported
      // occurrences; the ruling was written against the 78 that were reported. The other 7 have
      // identical evidence — none at all — but an approval is an approval of a set, not of a
      // predicate, and quietly extending it by seven would be deciding something the owner did
      // not. They are held and named instead.
      row.privateProvenanceReview = true
      if (ruledUnsupported.has(`${entityId} ${p.postNum}`)) {
        row.proposedAction = 'remove-annotation'
        row.certifiedCountEffect = -1
        row.withdrawalApproved = '2026-08-17 owner ruling — no text, URL, image or metadata supports this occurrence'
      } else {
        row.proposedAction = 'hold — same evidence as the approved 78, but outside the population the ruling named'
        row.beyondRuledPopulation = true
      }
    }

    rows.push(row)

    // ── the social-account dossier ─────────────────────────────────────────
    // Binding is asserted, not assumed. The handle identifies the entity only where the handle
    // itself spells the name; anything else stays unbound and goes to review rather than claiming
    // an identity the URL does not establish.
    if (v.category === 'social_account_reference') {
      const bound = completeTokenMatch(v.handle.replace(/[_.-]+/g, ' '), e.canonical)
        || glue(v.handle) === glue(e.canonical)
      socialAccounts.push({
        occurrenceId, postNum: p.postNum,
        platform: v.platform, handle: v.handle, url: v.url,
        entityId: bound ? entityId : null,
        displayName: e.canonical,
        matchedAlias: v.via,
        confidence: bound
          ? 'high — the handle spells the entity\'s canonical name'
          : `medium — the handle matches the registered alias "${v.via}" but not the canonical name; identity left for review`,
        migratedFrom: { layer: 'postAnalysis.namedEntities', occurrenceId, entityId, canonical: e.canonical, on: '2026-08-17', ruling: 'social handles are references, not prose mentions' },
      })
    }

    // ── the withdrawal dossier for the approved 78 ─────────────────────────
    // A withdrawal that cannot be explained line by line is not reversible in any way that
    // matters. Each row records what was searched for, where, and what came back empty.
    if (v.category === 'no_supported_provenance' && row.certifiedCountEffect === -1) {
      const f = postFacts(p)
      withdrawals.push({
        occurrenceId, postNum: p.postNum, index: i,
        entityId, canonical: e.canonical, entityType: e.type,
        alias, aliases: aliasesOf.get(entityId),
        priorClassification: 'no_supported_provenance (2026-08-16 record-level audit)',
        evidenceSearch: {
          renderedProse: 'every registered alias tested as a complete token — no match',
          quotedContent: f.quoted ? 'searched, no match' : 'the drop quotes nothing',
          urls: f.spans.length ? `${f.spans.length} link(s) searched by token and by glued brand — no match` : 'the drop carries no link',
          images: f.hasImage ? `${f.hasImage} image(s) attached — no OCR, caption, annotation or filename match` : 'the drop carries no image',
          metadata: Object.keys(f.meta).length ? `${Object.keys(f.meta).join(', ')} searched — no match` : 'no metadata fields carry text',
          substring: 'the alias does not even occur inside a longer word',
        },
        renderedDrop: f.rendered.slice(0, 400).replace(/\s+/g, ' '),
        withdrawalReason: 'No complete-token prose match, no URL-source relationship, no confirmed image evidence and no certified metadata basis. Approved for withdrawal by the owner on 2026-08-17.',
        reversal: `Insert "${alias}" at index ${i} of postAnalysis.namedEntities in #${p.postNum} (lowest index first) and add 1 to ${e.canonical}. Recorded in audit/entity-cleanup-reversal.json.`,
        certifiedCountEffect: -1,
        postTextUnchanged: true,
        mediaUnchanged: true,
      })
    }

    // ── the substring dossier the ruling asks for, per occurrence ───────────
    if (v.category === 'invalid_substring_extraction') {
      const f = postFacts(p)
      const word = v.containingWords[0]
      const at = f.rendered.indexOf(word)
      const rawAt = String(p.text ?? '').toLowerCase().indexOf(String(word).toLowerCase().slice(0, 12))
      substrings.push({
        occurrenceId,
        postNum: p.postNum,
        entityId,
        canonical: e.canonical,
        aliasThatMatched: alias,
        containingWords: v.containingWords,
        renderedContext: at >= 0 ? f.rendered.slice(Math.max(0, at - 60), at + word.length + 60).replace(/\s+/g, ' ') : null,
        rawContext: rawAt >= 0 ? String(p.text).slice(Math.max(0, rawAt - 60), rawAt + 80).replace(/\s+/g, ' ') : null,
        anotherValidAliasInProse: aliasesOf.get(entityId).find(a => completeTokenMatch(f.prose, a)) ?? null,
        urlProvenance: f.hosts.some(h => aliasesOf.get(entityId).some(a => gluedHostMatch(h, a))) ? f.hosts.join(', ') : null,
        imageProvenance: f.hasImage ? `${f.hasImage} image(s) attached, no OCR or annotation data in the corpus` : null,
        metadataProvenance: Object.keys(f.meta).find(k => aliasesOf.get(entityId).some(a => completeTokenMatch(f.meta[k], a))) ?? null,
        proposedAction: row.proposedAction,
        certifiedCountEffect: row.certifiedCountEffect,
        basis: 'The only place this alias occurs in the rendered drop is inside a longer word, and no complete-token alias, URL-source, image or metadata provenance supports the entity here. A drop carrying an image is NOT in this set — those are image_provenance_unconfirmed and stay certified.',
      })
    }
  }
}

