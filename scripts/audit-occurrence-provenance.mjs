// ── alias ownership ─────────────────────────────────────────────────────────
const aliasOwners = new Map()
for (const e of entities.entities) {
  for (const a of [...e.aliases.map(x => x.text), e.canonical]) {
    const k = a.toLowerCase()
    if (!aliasOwners.has(k)) aliasOwners.set(k, [])
    if (!aliasOwners.get(k).includes(e.id)) aliasOwners.get(k).push(e.id)
  }
}
const postsOf = new Map(entities.entities.map(e => [e.id, new Set(e.posts)]))
const aliasesOf = new Map(entities.entities.map(e =>
  [e.id, [...new Set([...e.aliases.map(a => a.text), e.canonical])]]))

const METADATA_FIELDS = ['subject', 'name', 'link', 'trip']

