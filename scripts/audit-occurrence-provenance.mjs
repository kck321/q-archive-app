// What supports EVERY certified entity occurrence in the archive — all 9,749 of them.
//
//   node scripts/audit-occurrence-provenance.mjs
//
// OWNER RULING, 2026-08-17. The boundary defect is not to be reviewed only among the 402 anchorless
// records. Every certified occurrence is classified, using every registered alias of its permanent
// entity id, against the RENDERED text — `scripts/lib/renderedMatch.mjs`, the one shared
// implementation. Nothing here changes a count: it produces the evidence a ruling is made from.
//
// THE UNIT IS THE OCCURRENCE, and that matters more than it sounds. `postAnalysis.namedEntities` is
// a list of alias strings per drop, with repeats — #2401 carries "WASH POST" three times. A hover
// record is one per (entity, post); a certified mention is one per ENTRY. Keying this audit on
// anything coarser would let one defect subtract two mentions, or two defects subtract the same
// mention twice. Every row below is identified by `#<post>:<index>` — the actual array position —
// so the integrated migration can deduplicate by the thing that is actually being removed.
//
// ATTRIBUTION IS NOT ASSUMED EITHER. 743 entries carry an alias that more than one live entity
// claims. Resolving them by alias alone would double-count; resolving them by "first match wins"
// would attribute dozens of mentions to a person Q may not have meant. So an entry is attributed
// only when exactly one entity claims that alias AND lists that drop. 61 entries survive as
// genuinely undecidable and are classified `ambiguous_provenance` — which is why 25 entities tally
// short of their certified figure, and that gap is reported rather than smoothed over.
